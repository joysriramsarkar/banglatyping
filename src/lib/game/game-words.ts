/** Get randomized word based on difficulty and optional conjunct boost */
export function getRandomGameWord(difficulty: GameDifficulty, includeConjuncts = false): string {
  let pool: string[];
  if (difficulty === 'easy') {
    pool = GAME_WORDS_EASY;
  } else if (difficulty === 'medium') {
    pool = includeConjuncts && Math.random() > 0.6 ? GAME_WORDS_CONJUNCTS : GAME_WORDS_MEDIUM;
  } else {
    pool = Math.random() > 0.4 ? GAME_WORDS_HARD : GAME_WORDS_CONJUNCTS;
  }
  return pool[Math.floor(Math.random() * pool.length)];
}

/** Get word by category */
export function getRandomGameWordByCategory(category: GameCategory, difficulty: GameDifficulty = 'medium'): string {
  let pool: string[];
  switch (category) {
    case 'basic':
      pool = difficulty === 'easy' ? GAME_WORDS_EASY : GAME_WORDS_MEDIUM;
      break;
    case 'conjuncts':
      pool = GAME_WORDS_CONJUNCTS;
      break;
    case 'phola':
      pool = GAME_WORDS_PHOLA;
      break;
    case 'numbers':
      pool = GAME_WORDS_NUMBERS;
      break;
    case 'punctuation':
      pool = GAME_WORDS_PUNCTUATION;
      break;
    case 'vocabulary':
      pool = difficulty === 'easy' ? GAME_WORDS_EASY : difficulty === 'medium' ? GAME_WORDS_MEDIUM : GAME_WORDS_HARD;
      break;
    default:
      pool = GAME_WORDS_MEDIUM;
  }
  return pool[Math.floor(Math.random() * pool.length)];
}

/** Get multiple unique words */
export function getRandomGameWords(count: number, difficulty: GameDifficulty): string[] {
  const selected = new Set<string>();
  let attempts = 0;
  while (selected.size < count && attempts < count * 5) {
    selected.add(getRandomGameWord(difficulty));
    attempts++;
  }
  return Array.from(selected);
}

/** Get random sentence by difficulty */
export function getRandomSentence(difficulty?: GameDifficulty): { id: string; text: string; category: string; difficulty: GameDifficulty } {
  let pool = GAME_SENTENCES;
  if (difficulty) {
    pool = GAME_SENTENCES.filter(s => s.difficulty === difficulty);
  }
  return pool[Math.floor(Math.random() * pool.length)];
}

/** Get random proverb */
export function getRandomProverb(): { id: string; text: string; meaning?: string } {
  return PROVERBS[Math.floor(Math.random() * PROVERBS.length)];
}
